FEM_HI = {'पुत्री','देवी','रानी','माता','पत्नी','कुमारी','कन्या','राजकुमारी','शक्ति','लक्ष्मी','सरस्वती','गंगा','पार्वती','दुर्गा','काली','गौरी','उमा','सीता','राधा','माला','वीणा','वाणी','कविता','किरण','ज्योति','शक्ति'}
FEM_NE = {'छोरी','देवी','रानी','आमा','पत्नी','कुमारी','कन्या','राजकुमारी','शक्ति','लक्ष्मी','सरस्वती','गंगा','पार्वती','दुर्गा','काली','गौरी','उमा','सीता','राधा'}

def _glue(head, lang):
    fem = FEM_NE if lang == 'ne' else FEM_HI
    is_fem = head.split(' ')[0] in fem
    if lang == 'hi':
        return 'की' if is_fem else 'के'
    return 'की' if is_fem else 'को'

def translate(en, lang):
    """Translate a short English meaning to hi (0) or ne (1)."""
    idx = 0 if lang == 'hi' else 1
    import re
    w = en.lower().strip()
    # possessive: X's Y -> X के Y
    m = re.match(r"^([a-z']+)'s (.+)$", w)
    if m:
        a = G.get(m.group(1), (m.group(1), m.group(1)))[idx]
        b = translate(m.group(2), lang)
        return (a + ' ' + _glue(b, lang) + ' ' + b).strip()
    # X of Y -> Y के X
    m = re.match(r'^(.+?) of (.+)$', w)
    if m:
        a = translate(m.group(1), lang)
        b = translate(m.group(2), lang)
        return (b + ' ' + _glue(a, lang) + ' ' + a).strip()
    # word by word
    toks = re.findall(r"[a-z']+", w)
    out = []
    for t in toks:
        if t in G:
            v = G[t][idx]
            if v:
                out.append(v)
        else:
            out.append(t)  # fallback: keep English
    s = ' '.join(out)
    s = re.sub(r'\s+', ' ', s).strip()
    return s[0].upper() + s[1:] if s else s
